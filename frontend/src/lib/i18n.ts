const messages: Record<Language, Record<BaseMessageKey, string>> = {
  'zh-CN': zhCN,
  'zh-TW': zhTW,
  en,
  ja,
  ko,
};

export function matchLanguage(value: string | null | undefined): Language | null {
  if (!value) return null;
  const normalized = value.trim().toLowerCase().replace(/_/g, '-');
  if (normalized.startsWith('zh')) {
    if (
      normalized.includes('tw') ||
      normalized.includes('hk') ||
      normalized.includes('mo') ||
      normalized.includes('hant')
    ) {
      return 'zh-TW';
    }
    return 'zh-CN';
  }
  if (normalized.startsWith('en')) return 'en';
  if (normalized.startsWith('ja')) return 'ja';
  if (normalized.startsWith('ko')) return 'ko';
  return null;
}

export function normalizeLanguage(value: string | null | undefined): Language {
  return matchLanguage(value) ?? 'zh-CN';
}

export function detectSystemLanguage(): Language {
  if (typeof navigator === 'undefined') return 'zh-CN';
  const candidates = [navigator.language, ...(navigator.languages ?? [])];
  for (const candidate of candidates) {
    const matched = matchLanguage(candidate);
    if (matched) return matched;
  }
  return 'zh-CN';
}

export function resolveStartupLanguage(auto: boolean, configured: string): Language {
  return auto ? detectSystemLanguage() : normalizeLanguage(configured);
}

export function translate(
  language: Language,
  key: MessageKey,
  vars?: Record<string, string | number>,
): string {
  const baseKey = key as BaseMessageKey;
  const extraKey = key as ExtraMessageKey;
  let text = messages[language][baseKey]
    ?? extraMessages[language][extraKey]
    ?? messages['zh-CN'][baseKey]
    ?? extraMessages['zh-CN'][extraKey]
    ?? key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.split(`{${name}}`).join(String(value));
    }
  }
  return text;
}

export function localeFor(language: Language): string {
  return language;
}

export function accountKindKey(kind: string): MessageKey {
  if (kind === 'microsoft') return 'account.kind.microsoft';
  if (kind === 'authlib') return 'account.kind.authlib';
  return 'account.kind.offline';
}
