// Package serverpack builds a ready-to-configure Minecraft server archive from
// an instance's mods, configs, and loader runtime.
package serverpack

import (
	"archive/zip"
	"context"
	"encoding/json"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"strings"
	"time"

	"MyMinecraftGoLuncher/internal/httpx"
	"MyMinecraftGoLuncher/internal/loader"
	"MyMinecraftGoLuncher/internal/mojang"
	"MyMinecraftGoLuncher/internal/store"
)

// ProgressFunc receives coarse export progress updates.
type ProgressFunc func(stage, message string, current, total int)

// Options controls one server-pack export.
type Options struct {
	Client    *mojang.Client
	Instance  store.Instance
	GameDir   string
	Dest      string
	JavaMajor int
	Progress  ProgressFunc
}

// Result describes a completed export.
type Result struct {
	Path     string   `json:"path"`
	Warnings []string `json:"warnings"`
}

const (
	runtimeVanilla          = "vanilla"
	runtimeFabric           = "fabric"
	runtimeFabricInstaller  = "fabric-installer"
	runtimeQuiltInstaller   = "quilt-installer"
	runtimeForgeInstaller   = "forge-installer"
	serverPropertiesDefault = "# Generated by MyGoLuncher\nserver-port=25565\nonline-mode=true\nmotd=MyGoLuncher Server\n"
)

var contentDirs = []string{
	"mods", "config", "defaultconfigs", "scripts", "kubejs", "datapacks", "resourcepacks",
}

var contentFiles = []string{
	"server.properties", "ops.json", "whitelist.json", "banned-ips.json",
	"banned-players.json", "server-icon.png", "icon.png",
}

// Export downloads the loader runtime and writes a server pack zip.
func Export(ctx context.Context, opts Options) (Result, error) {
	dest := strings.TrimSpace(opts.Dest)
	if dest == "" {
		return Result{}, fmt.Errorf("导出路径为空")
	}
	if !strings.HasSuffix(strings.ToLower(dest), ".zip") {
		dest += ".zip"
	}
	tempDir, err := os.MkdirTemp("", "mygoluncher-serverpack-*")
	if err != nil {
		return Result{}, err
	}
	defer os.RemoveAll(tempDir)

	result := Result{Warnings: []string{}}
	progress := opts.Progress
	if progress == nil {
		progress = func(string, string, int, int) {}
	}
	if loaderType := strings.ToLower(strings.TrimSpace(opts.Instance.Loader)); loaderType != "" &&
		loaderType != "vanilla" && strings.TrimSpace(opts.Instance.LoaderVersion) == "" {
		if resolved, err := loader.LatestVersion(ctx, loaderType, opts.Instance.MCVersion); err == nil {
			opts.Instance.LoaderVersion = resolved
		}
	}
	progress("runtime", "正在准备服务器运行时…", 0, 0)
	runtimePath, runtimeName, runtimeKind, warnings := downloadRuntime(ctx, opts, tempDir, progress)
	result.Warnings = append(result.Warnings, warnings...)

	progress("pack", "正在打包模组与配置…", 0, 0)
	destDir := filepath.Dir(dest)
	if err := os.MkdirAll(destDir, 0o755); err != nil {
		return result, err
	}
	tempZip, err := os.CreateTemp(destDir, ".serverpack-*.zip")
	if err != nil {
		return result, err
	}
	tempName := tempZip.Name()
	defer os.Remove(tempName)

	zw := zip.NewWriter(tempZip)
	writeErr := writePack(zw, opts, runtimePath, runtimeName, runtimeKind, result.Warnings)
	if writeErr == nil {
		writeErr = zw.Close()
	} else {
		_ = zw.Close()
	}
	closeErr := tempZip.Close()
	if writeErr != nil {
		return result, writeErr
	}
	if closeErr != nil {
		return result, closeErr
	}
	_ = os.Remove(dest)
	if err := os.Rename(tempName, dest); err != nil {
		return result, err
	}
	result.Path = dest
	progress("done", "服务器包导出完成", 1, 1)
	return result, nil
}

func downloadRuntime(ctx context.Context, opts Options, tempDir string, progress ProgressFunc) (path, name, kind string, warnings []string) {
	inst := opts.Instance
	loaderType := strings.ToLower(strings.TrimSpace(inst.Loader))
	if loaderType == "" {
		loaderType = "vanilla"
	}
	loaderVersion := strings.TrimSpace(inst.LoaderVersion)
	if loaderType != "vanilla" && loaderVersion == "" {
		resolved, err := loader.LatestVersion(ctx, loaderType, inst.MCVersion)
		if err == nil {
			loaderVersion = resolved
		}
	}
	download := func(url, filename string, file httpx.File) (string, bool) {
		file.URL = url
		file.Dest = filepath.Join(tempDir, filename)
		file.Progress = func(done, total int64) {
			progress("runtime", "正在下载服务器运行时…", int(done), int(total))
		}
		if err := httpx.Download(ctx, file); err != nil {
			warnings = append(warnings, fmt.Sprintf("服务器运行时 %s 下载失败: %v", filename, err))
			return "", false
		}
		return file.Dest, true
	}

	switch loaderType {
	case "fabric":
		url, err := loader.FabricServerLauncherURL(ctx, inst.MCVersion, loaderVersion)
		if err == nil {
			if path, ok := download(url, "fabric-server-launch.jar", httpx.File{}); ok {
				return path, "fabric-server-launch.jar", runtimeFabric, warnings
			}
		} else {
			warnings = append(warnings, "无法获取 Fabric 服务端启动器: "+err.Error())
		}
		installerURL, err := loader.FabricInstallerURL(ctx)
		if err == nil {
			if path, ok := download(installerURL, "fabric-installer.jar", httpx.File{}); ok {
				warnings = append(warnings, "已将 Fabric 安装器放入服务器包，请先运行 install-server 脚本。")
				return path, "fabric-installer.jar", runtimeFabricInstaller, warnings
			}
		} else {
			warnings = append(warnings, "无法获取 Fabric 安装器: "+err.Error())
		}
	case "quilt":
		url, err := loader.QuiltInstallerURL(ctx)
		if err == nil {
			if path, ok := download(url, "quilt-installer.jar", httpx.File{}); ok {
				return path, "quilt-installer.jar", runtimeQuiltInstaller, warnings
			}
		} else {
			warnings = append(warnings, "无法获取 Quilt 安装器: "+err.Error())
		}
	case "forge", "neoforge":
		url, err := loader.ForgeInstallerURL(inst.MCVersion, loaderType, loaderVersion)
		if err != nil {
			warnings = append(warnings, "无法获取加载器安装器: "+err.Error())
			break
		}
		filename := "forge-installer.jar"
		if loaderType == "neoforge" {
			filename = "neoforge-installer.jar"
		}
		if path, ok := download(url, filename, httpx.File{}); ok {
			return path, filename, runtimeForgeInstaller, warnings
		}
	default:
		version, err := opts.Client.EnsureVersion(ctx, inst.MCVersion)
		if err != nil {
			warnings = append(warnings, "无法读取 Minecraft 版本元数据: "+err.Error())
			break
		}
		server, ok := version.Downloads["server"]
		if !ok || strings.TrimSpace(server.URL) == "" {
			warnings = append(warnings, "该 Minecraft 版本没有可用的官方服务端。")
			break
		}
		if path, ok := download(server.URL, "server.jar", httpx.File{SHA1: server.SHA1, Size: server.Size}); ok {
			return path, "server.jar", runtimeVanilla, warnings
		}
	}
	warnings = append(warnings, "服务器包已包含模组与配置，但未包含运行时文件。请按 README 手动补充服务端。")
	return "", "", "missing", warnings
}

func writePack(zw *zip.Writer, opts Options, runtimePath, runtimeName, runtimeKind string, warnings []string) error {
	inst := opts.Instance
	progress := opts.Progress
	if progress == nil {
		progress = func(string, string, int, int) {}
	}
	for _, dir := range contentDirs {
		src := filepath.Join(opts.GameDir, dir)
		if info, err := os.Stat(src); err != nil || !info.IsDir() {
			continue
		}
		if err := addDir(zw, src, dir); err != nil {
			return err
		}
	}
	for _, name := range contentFiles {
		src := filepath.Join(opts.GameDir, name)
		if info, err := os.Stat(src); err != nil || info.IsDir() {
			continue
		}
		if err := addFile(zw, src, name); err != nil {
			return err
		}
	}
	if _, err := os.Stat(filepath.Join(opts.GameDir, "server.properties")); err != nil {
		if err := addBytes(zw, "server.properties", []byte(serverPropertiesDefault), 0o644); err != nil {
			return err
		}
	}
	if err := addBytes(zw, "eula.txt", []byte("# https://aka.ms/MinecraftEULA\neula=false\n"), 0o644); err != nil {
		return err
	}
	if runtimePath != "" && runtimeName != "" {
		if err := addFile(zw, runtimePath, runtimeName); err != nil {
			return err
		}
	}
	for _, file := range scriptsFor(runtimeKind, inst) {
		if err := addBytes(zw, file.name, []byte(file.body), file.mode); err != nil {
			return err
		}
	}
	manifest := map[string]any{
		"minecraft":     inst.MCVersion,
		"loader":        inst.Loader,
		"loaderVersion": inst.LoaderVersion,
		"java":          opts.JavaMajor,
		"runtime":       runtimeKind,
		"createdAt":     time.Now().Format(time.RFC3339),
		"warnings":      warnings,
	}
	manifestBytes, _ := json.MarshalIndent(manifest, "", "  ")
	if err := addBytes(zw, "server-pack.json", manifestBytes, 0o644); err != nil {
		return err
	}
	readme := readmeFor(inst, opts.JavaMajor, runtimeKind, warnings)
	if err := addBytes(zw, "README.txt", []byte(readme), 0o644); err != nil {
		return err
	}
	progress("pack", "服务器包内容已写入", 1, 1)
	return nil
}

type scriptFile struct {
	name string
	body string
	mode os.FileMode
}

func scriptsFor(runtimeKind string, inst store.Instance) []scriptFile {
	java := "java -Xms1G -Xmx4G"
	switch runtimeKind {
	case runtimeFabric:
		return []scriptFile{
			{"start.bat", "@echo off\r\n" + java + " -jar fabric-server-launch.jar nogui\r\npause\r\n", 0o644},
			{"start.sh", "#!/usr/bin/env sh\nexec " + java + " -jar fabric-server-launch.jar nogui\n", 0o755},
		}
	case runtimeFabricInstaller:
		installBat := fmt.Sprintf("@echo off\r\njava -jar fabric-installer.jar server -mcversion %s -loader %s -downloadMinecraft\r\npause\r\n", inst.MCVersion, inst.LoaderVersion)
		installSh := fmt.Sprintf("#!/usr/bin/env sh\njava -jar fabric-installer.jar server -mcversion %s -loader %s -downloadMinecraft\n", inst.MCVersion, inst.LoaderVersion)
		return []scriptFile{
			{"install-server.bat", installBat, 0o644},
			{"install-server.sh", installSh, 0o755},
			{"start.bat", startWithJarCheck("fabric-server-launch.jar", java), 0o644},
			{"start.sh", startShellWithJarCheck("fabric-server-launch.jar", java), 0o755},
		}
	case runtimeQuiltInstaller:
		installBat := fmt.Sprintf("@echo off\r\njava -jar quilt-installer.jar install server %s %s --create-scripts --download-server\r\npause\r\n", inst.MCVersion, inst.LoaderVersion)
		installSh := fmt.Sprintf("#!/usr/bin/env sh\njava -jar quilt-installer.jar install server %s %s --create-scripts --download-server\n", inst.MCVersion, inst.LoaderVersion)
		return []scriptFile{
			{"install-server.bat", installBat, 0o644},
			{"install-server.sh", installSh, 0o755},
			{"start.bat", startWithJarCheck("quilt-server-launch.jar", java), 0o644},
			{"start.sh", startShellWithJarCheck("quilt-server-launch.jar", java), 0o755},
		}
	case runtimeForgeInstaller:
		installer := "forge-installer.jar"
		if strings.EqualFold(inst.Loader, "neoforge") {
			installer = "neoforge-installer.jar"
		}
		installBat := fmt.Sprintf("@echo off\r\njava -jar %s --installServer\r\npause\r\n", installer)
		installSh := fmt.Sprintf("#!/usr/bin/env sh\njava -jar %s --installServer\n", installer)
		return []scriptFile{
			{"install-server.bat", installBat, 0o644},
			{"install-server.sh", installSh, 0o755},
			{"start.bat", forgeStartBat(java), 0o644},
			{"start.sh", forgeStartSh(java), 0o755},
		}
	default:
		return []scriptFile{
			{"start.bat", "@echo off\r\n" + java + " -jar server.jar nogui\r\npause\r\n", 0o644},
			{"start.sh", "#!/usr/bin/env sh\nexec " + java + " -jar server.jar nogui\n", 0o755},
		}
	}
}

func startWithJarCheck(jar, java string) string {
	return "@echo off\r\nif not exist " + jar + " (\r\n  echo Please run install-server.bat first.\r\n  pause\r\n  exit /b 1\r\n)\r\n" + java + " -jar " + jar + " nogui\r\npause\r\n"
}

func startShellWithJarCheck(jar, java string) string {
	return "#!/usr/bin/env sh\nif [ ! -f " + jar + " ]; then\n  echo \"Please run install-server.sh first.\"\n  exit 1\nfi\nexec " + java + " -jar " + jar + " nogui\n"
}

func forgeStartBat(java string) string {
	return "@echo off\r\nif exist run.bat (\r\n  call run.bat\r\n  goto :eof\r\n)\r\n" +
		"for %%f in (forge-*.jar neoforge-*.jar) do (\r\n  if exist \"%%f\" (\r\n    " + java + " -jar \"%%f\" nogui\r\n    goto :eof\r\n  )\r\n)\r\n" +
		"echo Please run install-server.bat first.\r\npause\r\n"
}

func forgeStartSh(java string) string {
	return "#!/usr/bin/env sh\nif [ -f run.sh ]; then exec sh run.sh; fi\n" +
		"for jar in forge-*.jar neoforge-*.jar; do\n  if [ -f \"$jar\" ]; then exec " + java + " -jar \"$jar\" nogui; fi\ndone\n" +
		"echo \"Please run install-server.sh first.\"\n"
}

func readmeFor(inst store.Instance, javaMajor int, runtimeKind string, warnings []string) string {
	var b strings.Builder
	b.WriteString("MyGoLuncher Server Pack\n")
	b.WriteString("=======================\n\n")
	fmt.Fprintf(&b, "Minecraft: %s\n", inst.MCVersion)
	fmt.Fprintf(&b, "Loader: %s %s\n", firstNonEmpty(inst.Loader, "vanilla"), inst.LoaderVersion)
	fmt.Fprintf(&b, "Java: %d\n\n", javaMajor)
	b.WriteString("Usage / 使用说明\n")
	b.WriteString("1. Read the Minecraft EULA and set eula=true in eula.txt.\n")
	b.WriteString("   阅读 Minecraft EULA 后，将 eula.txt 中的 eula=false 改为 true。\n")
	switch runtimeKind {
	case runtimeForgeInstaller:
		b.WriteString("2. Run install-server.bat (Windows) or install-server.sh once.\n")
		b.WriteString("   首次运行 install-server 脚本安装加载器。\n")
		b.WriteString("3. Start the server with start.bat or start.sh.\n")
		b.WriteString("   然后运行 start 脚本启动服务器。\n")
	case runtimeQuiltInstaller, runtimeFabricInstaller:
		b.WriteString("2. Run install-server.bat (Windows) or install-server.sh once.\n")
		b.WriteString("   首次运行 install-server 脚本安装加载器。\n")
		b.WriteString("3. Start the server with start.bat or start.sh.\n")
		b.WriteString("   然后运行 start 脚本启动服务器。\n")
	default:
		b.WriteString("2. Start the server with start.bat or start.sh.\n")
		b.WriteString("   运行 start 脚本启动服务器。\n")
	}
	b.WriteString("\nAdjust -Xms/-Xmx in the start script to match your server memory.\n")
	b.WriteString("请根据服务器内存调整 start 脚本中的 -Xms/-Xmx。\n")
	b.WriteString("Client-only mods may need to be removed from mods/.\n")
	b.WriteString("仅客户端模组可能需要从 mods/ 中移除。\n")
	if len(warnings) > 0 {
		b.WriteString("\nWarnings / 警告\n")
		for _, warning := range warnings {
			b.WriteString("- " + warning + "\n")
		}
	}
	return b.String()
}

func firstNonEmpty(values ...string) string {
	for _, value := range values {
		if strings.TrimSpace(value) != "" {
			return strings.TrimSpace(value)
		}
	}
	return ""
}

func addDir(zw *zip.Writer, root, prefix string) error {
	return filepath.WalkDir(root, func(path string, entry os.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if entry.IsDir() {
			return nil
		}
		if !entry.Type().IsRegular() {
			return nil
		}
		rel, err := filepath.Rel(root, path)
		if err != nil {
			return err
		}
		return addFile(zw, path, filepath.ToSlash(filepath.Join(prefix, rel)))
	})
}

func addFile(zw *zip.Writer, path, name string) error {
	info, err := os.Stat(path)
	if err != nil {
		return err
	}
	header, err := zip.FileInfoHeader(info)
	if err != nil {
		return err
	}
	header.Name = filepath.ToSlash(name)
	header.Method = zip.Deflate
	writer, err := zw.CreateHeader(header)
	if err != nil {
		return err
	}
	file, err := os.Open(path)
	if err != nil {
		return err
	}
	defer file.Close()
	_, err = io.Copy(writer, file)
	return err
}

func addBytes(zw *zip.Writer, name string, data []byte, mode os.FileMode) error {
	header := &zip.FileHeader{Name: name, Method: zip.Deflate}
	header.SetMode(mode)
	writer, err := zw.CreateHeader(header)
	if err != nil {
		return err
	}
	_, err = writer.Write(data)
	return err
}
